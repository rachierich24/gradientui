const http = require('http');
const fs = require('fs');

async function getWsUrl() {
  return new Promise((resolve, reject) => {
    http.get('http://localhost:9222/json', (res) => {
      let data = '';
      res.on('data', chunk => data += chunk);
      res.on('end', () => {
        const tabs = JSON.parse(data);
        const tab = tabs.find(t => t.url.includes('localhost:3000'));
        if (tab) resolve(tab.webSocketDebuggerUrl);
        else reject(new Error('Tab not found'));
      });
    }).on('error', reject);
  });
}

function send(ws, method, params = {}) {
  return new Promise((resolve, reject) => {
    const id = Math.floor(Math.random() * 1000000);
    const handler = (event) => {
      try {
        const raw = typeof event.data === 'string' ? event.data : event.data.toString();
        const msg = JSON.parse(raw);
        if (msg.id === id) {
          ws.removeEventListener('message', handler);
          if (msg.error) reject(msg.error);
          else resolve(msg.result);
        }
      } catch (e) {}
    };
    ws.addEventListener('message', handler);
    ws.send(JSON.stringify({ id, method, params }));
  });
}

async function run() {
  const wsUrl = await getWsUrl();
  const ws = new WebSocket(wsUrl);
  await new Promise(r => ws.onopen = r);

  await send(ws, 'Runtime.evaluate', {
    expression: `
      const btn = document.querySelector('.eco-macbook-lid-btn');
      if (btn) btn.click();
    `
  });
  await new Promise(r => setTimeout(r, 600));

  let ss = await send(ws, 'Page.captureScreenshot', { format: 'png' });
  fs.writeFileSync('scratch/macbook_lid_closed_state.png', Buffer.from(ss.data, 'base64'));
  console.log('Saved scratch/macbook_lid_closed_state.png');

  ws.close();
}

run().catch(console.error);
